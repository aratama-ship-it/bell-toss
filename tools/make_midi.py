# notes: (beat, midi, dur_beats)。beatUnit='eighth' の曲は1拍=8分音符
def merge_repeats(notes, min_gap_beats):
    """隣接する同音を統合する。投鈴は1キャッチ1音なので、min_gap 未満の間隔で
    同じ音を鳴らし直すことは物理的にできない（キャッチ+投げ+滞空 が必要）。
    前の音を伸ばして1音にまとめる＝楽譜のタイと同じ扱い。既存曲の編曲時に使う。"""
    notes = sorted(notes, key=lambda x: (x[0], x[1]))
    out = []
    for b, m, d in notes:
        merged = False
        for i in range(len(out) - 1, -1, -1):
            pb, pm, pd = out[i]
            if b - pb > min_gap_beats * 2:
                break
            if pm == m and b - pb < min_gap_beats:
                out[i] = (pb, pm, max(pd, b + d - pb))
                merged = True
                break
        if not merged:
            out.append((b, m, d))
    return out


def cycle_phrases(scale, plan, min_gap_beats):
    """巡回パターンで旋律を組み立てる。投鈴の要点は「同音の再出現間隔」で、
    これが キャッチ+投げ+滞空 を下回るとリングを複製せざるを得ず、手元が埋まって
    パスができなくなる。この関数は min_gap_beats を必ず満たすことを検査する。

    plan の要素: ('cycle', 巡回順(添字), 1音の拍数, 反復回数) / ('rest', 拍数)
    フレーズの切れ目に 'rest' を挟むと、巡回順を変えても間隔条件を保てる。
    """
    notes = []
    beat = 0.0
    last = {}
    for item in plan:
        if item[0] == "rest":
            beat += item[1]
            continue
        _, order, dur, reps = item
        for _ in range(reps):
            for idx in order:
                m = scale[idx]
                if m in last and beat - last[m] < min_gap_beats - 1e-9:
                    raise ValueError(f"同音間隔が不足: {m} at beat {beat}")
                notes.append((beat, m, dur))
                last[m] = beat
                beat += dur
    return notes


