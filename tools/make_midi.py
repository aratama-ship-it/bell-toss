def vlq(n):
    out = [n & 0x7F]
    n >>= 7
    while n:
        out.insert(0, (n & 0x7F) | 0x80)
        n >>= 7
    return bytes(out)


def track_chunk(events):
    events.sort(key=lambda e: e[0])
    data = b""
    last = 0
    for tick, ev in events:
        data += vlq(max(0, int(round(tick - last)))) + ev
        last = tick
    data += b"\x00\xff\x2f\x00"
    return b"MTrk" + struct.pack(">I", len(data)) + data


def build_midi(song):
    ticks_per_beat = TPQ if song["beatUnit"] == "quarter" else TPQ // 2
    us_per_quarter = int(round(60_000_000 / song["bpm"] * (TPQ / ticks_per_beat)))

    tempo_ev = [(0, b"\xff\x51\x03" + struct.pack(">I", us_per_quarter)[1:])]
    dd = 2 if song["beatUnit"] == "quarter" else 3
    tempo_ev.append((0, b"\xff\x58\x04" + bytes([song["beatsPerBar"], dd, 24, 8])))

    mel = [(0, b"\xff\x03" + bytes([len(song["id"])]) + song["id"].encode())]
    mel.append((0, b"\xc0\x0e"))  # program 14: tubular bells
    for beat, midi, dur in song["notes"]:
        t = beat * ticks_per_beat
        mel.append((t, bytes([0x90, midi, 96])))
        mel.append((t + dur * ticks_per_beat, bytes([0x80, midi, 0])))

    header = b"MThd" + struct.pack(">IHHH", 6, 1, 2, TPQ)
    return header + track_chunk(tempo_ev) + track_chunk(mel)


def make_songs_js():
    lines = [
        "/* 投鈴 — ジャグリング映え重視の楽曲プリセット",
        "   ※このファイルは tools/make_midi.py が生成する。直接編集しない。 */",
        '"use strict";', "",
        "TOREI.SONGS = [",
    ]
    for s in SONGS:
        notes = ",".join(
            f"{{beat:{b},midi:{m}}}" for b, m, d in s["notes"]
        )
        hidden = "true" if s.get("hidden") else "false"
        # maxDup は常に明示する（2026-08-24 修正）。曲を切り替えても「前の曲の値を
        # 引き継ぐ」流儀は他の推奨設定（flight等）と同じだが、maxDup だけは値の違いが
        # 再生可否そのものを左右するため、無指定＝引き継ぎのままだと「ぶんぶんぶんを見た後
        # 他の曲へ切り替えると成立しなくなる」事故が起きた（実機で11曲を確認）。
        # 全曲へ検証済みの値（既定2、ぶんぶんぶんのみ1）を明示することで解決する。
        lines.append(
            f'  {{ id: "{s["id"]}", name: "{s["name"]}", bpm: {s["bpm"]},'
            f' beatsPerBar: {s["beatsPerBar"]}, performers: {s.get("performers", 4)},'
            f' passMode: "{s.get("passMode", "more")}", standTime: {s.get("standTime", 2.0)},'
            f' flight: {s.get("flight", 1.2)}, maxDup: {s.get("maxDup", 2)}, hidden: {hidden},'
        )
        lines.append(f"    notes: [{notes}] }},")
    lines += [
        "];", "",
        "// 既存プリセットの前に挿入（新しい曲を上に）",
        "TOREI.PRESETS = [...TOREI.SONGS, ...TOREI.PRESETS];", "",
    ]
    return "\n".join(lines)


def check_song(song):
    """同音の再出現間隔と使用音高数を検証し、問題を文字列リストで返す。
    目安: 使用音高数 <= 人数x3（脇1本前提）／同音間隔は投げが成立する 2.4秒以上。"""
    spb = 60 / song["bpm"] * (1 if song["beatUnit"] == "quarter" else 0.5)
    # 同時刻に2音以上ある拍。ここに載る音は「保持キャッチ和音」で鳴りうる＝投げ直しが
    # 不要になる場合があるため、同音間隔の警告から外す（外さないと偽の警告が出る）。
    from collections import Counter
    chord_beats = {b for b, c in Counter(b for b, _, _ in song["notes"]).items() if c >= 2}
    last = {}
    tight = []
    chord_exempt = 0
    for beat, midi, _ in sorted(song["notes"]):
        t = beat * spb
        if midi in last:
            gap = t - last[midi]
            if gap < 2.4:
                if beat in chord_beats:
                    chord_exempt += 1
                else:
                    tight.append((round(beat, 2), midi, round(gap, 2)))
        last[midi] = t
    issues = []
    pitches = len({m for _, m, _ in song["notes"]})
    if tight:
        issues.append(f"同音間隔が短い箇所 {len(tight)}件 (最小 {min(g for _, _, g in tight)}秒): {tight[:3]}")
    if chord_exempt:
        issues.append(f"同音間隔が短いが和音の拍なので除外 {chord_exempt}件"
                      f"（保持キャッチ和音なら投げ直しが要らない。tools/analyze.mjs で成否を確認すること）")
    issues.append(f"使用音高 {pitches} → 必要人数の目安 {-(-pitches // 3)}人以上")
    return issues


